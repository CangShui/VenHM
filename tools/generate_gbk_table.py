"""Generate a sorted Unicode->GBK mapping for the native module.

Python's standard-library GBK codec is used only at build time. The generated
header is vendored so the app does not depend on iconv_open('GBK') being
available on a given HarmonyOS device.

Run: python tools/generate_gbk_table.py
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / 'entry' / 'src' / 'main' / 'cpp' / 'gbk_table.h'
rows = []
for codepoint in range(0x80, 0x10000):
    if 0xD800 <= codepoint <= 0xDFFF:
        continue
    try:
        encoded = chr(codepoint).encode('gbk')
    except UnicodeEncodeError:
        continue
    if len(encoded) == 2:
        rows.append((codepoint << 16) | (encoded[0] << 8) | encoded[1])
    elif len(encoded) == 1:
        raise AssertionError(f'unexpected single byte for U+{codepoint:04X}')

with OUTPUT.open('w', encoding='ascii', newline='\n') as file:
    file.write('/* Generated by tools/generate_gbk_table.py from Python gbk. */\n')
    file.write('#ifndef VENERA_GBK_TABLE_H\n#define VENERA_GBK_TABLE_H\n')
    file.write('#include <cstdint>\n#include <cstddef>\nnamespace venera {\n')
    file.write('static constexpr uint32_t kGbkPairs[] = {\n')
    for pos in range(0, len(rows), 8):
        file.write('  ' + ', '.join(f'0x{row:08x}u' for row in rows[pos:pos+8]) + ',\n')
    file.write('};\n')
    file.write('static constexpr size_t kGbkPairCount = sizeof(kGbkPairs) / sizeof(kGbkPairs[0]);\n')
    file.write('} // namespace venera\n#endif // VENERA_GBK_TABLE_H\n')
print(f'{OUTPUT}: {len(rows)} GBK pairs')
